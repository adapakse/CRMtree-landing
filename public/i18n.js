  function getByPath(obj, path) {
    var parts = path.split(".");
    var cur = obj;
    for (var i = 0; i < parts.length; i++) {
      if (cur == null) return null;
      cur = cur[parts[i]];
    }
    return cur;
  }

  function detectLang() {
    try {
      var saved = localStorage.getItem(STORAGE_KEY);
      if (saved && I18N[saved]) return saved;
    } catch (e) {}
    var nav = (navigator.language || "pl").slice(0, 2).toLowerCase();
    for (var i = 0; i < LANGS.length; i++) {
      if (LANGS[i].code === nav) return nav;
    }
    return "pl";
  }

  function applyLang(code) {
    if (!I18N[code]) code = "pl";
    var table = I18N[code];
    var fallback = I18N.pl;
    document.documentElement.setAttribute("lang", code);

    var nodes = document.querySelectorAll("[data-i18n]");
    for (var i = 0; i < nodes.length; i++) {
      var key = nodes[i].getAttribute("data-i18n");
      var val = getByPath(table, key);
      if (val == null) val = getByPath(fallback, key); // graceful fallback to Polish
      if (val != null) nodes[i].textContent = val;
    }

    var attrNodes = document.querySelectorAll("[data-i18n-placeholder]");
    for (var j = 0; j < attrNodes.length; j++) {
      var pkey = attrNodes[j].getAttribute("data-i18n-placeholder");
      var pval = getByPath(table, pkey);
      if (pval == null) pval = getByPath(fallback, pkey);
      if (pval != null) attrNodes[j].setAttribute("placeholder", pval);
    }

    try { localStorage.setItem(STORAGE_KEY, code); } catch (e) {}

    var btnLabel = document.getElementById("langBtnLabel");
    if (btnLabel) btnLabel.textContent = code.toUpperCase();
    var menuBtns = document.querySelectorAll("#langMenu button");
    for (var k = 0; k < menuBtns.length; k++) {
      menuBtns[k].setAttribute("aria-current", menuBtns[k].getAttribute("data-code") === code ? "true" : "false");
    }
  }

  function buildLangMenu() {
    var menu = document.getElementById("langMenu");
    var btn = document.getElementById("langBtn");
    if (!menu || !btn) return;
    LANGS.forEach(function (l) {
      var b = document.createElement("button");
      b.type = "button";
      b.setAttribute("data-code", l.code);
      b.innerHTML = "<span>" + l.name + "</span><span class=\"lang-code\">" + l.code.toUpperCase() + "</span>";
      b.addEventListener("click", function () {
        applyLang(this.getAttribute("data-code"));
        menu.classList.remove("open");
        btn.setAttribute("aria-expanded", "false");
      });
      menu.appendChild(b);
    });
    btn.addEventListener("click", function () {
      var open = menu.classList.toggle("open");
      btn.setAttribute("aria-expanded", open ? "true" : "false");
    });
    document.addEventListener("click", function (e) {
      if (!menu.contains(e.target) && e.target !== btn && !btn.contains(e.target)) {
        menu.classList.remove("open");
        btn.setAttribute("aria-expanded", "false");
      }
    });
  }

  document.addEventListener("DOMContentLoaded", function () {
    buildLangMenu();
    applyLang(detectLang());
  });

  window.CRMtreeI18N = { apply: applyLang, langs: LANGS };
